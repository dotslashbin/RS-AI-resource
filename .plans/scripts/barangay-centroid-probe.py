#!/usr/bin/env python3
"""
Measure whether the `psgc` package's barangay coordinates are usable as a
barangay-centroid table for booker  —  plan .plans/2026-10-16-booker-barangay-near.md, U1.

WHY THIS EXISTS
U1 asked whether a licensed, PSGC-keyed barangay centroid dataset exists. Reading the
sources alone produced a WRONG answer, and this script is what corrected it:

  * OCHA HDX COD-AB (`cod-ab-phl`, CC BY-IGO) states in its own dataset notes
    "Admin 4: 11920" — 11,920 of the 42,046 barangays these apps ship, i.e. 28.3%.
  * The `psgc` PyPI package claims 42,010 barangay coordinates and names COD-AB as its
    boundary source.
  * From those two facts it was INFERRED that ~72% of the package's coordinates must be
    derived from coarser (city/province) polygons — "the city centroid in a barangay's
    clothing", the same failure class as the near-me plan's F14.
  * ⚠️ THE INFERENCE WAS WRONG. Measured: 87.5% carry exact HDX geometry, only 0.2% are
    flagged unverified, and essentially none (2 of 42,010) equal the parent city's
    coordinate. The arithmetic was sound; the premise ("11920 is all the admin-4 geometry
    that exists") was not — the package's rows are labelled `hdx_exact_2023`, a 2023
    vintage, while that note describes the current version-03 dataset.

The lesson is the reason this file is committed rather than thrown away: an upper bound
inferred from two documents is not a measurement, and it took one afternoon's arithmetic
from "plausible" to "stated as fact in two plans".

HOW TO RUN  (the package is NOT an app dependency and must never become one — booker is
TypeScript; this is an offline investigation, and any shipped asset would be generated by a
script like `build-ph-city-centroids.py`, not by importing this at runtime)

    python3 -m venv /tmp/psgc-probe/venv
    /tmp/psgc-probe/venv/bin/pip install psgc            # 41 MB installed, v2026.4.13.0
    D=/tmp/psgc-probe/venv/lib/python3.*/site-packages/psgc/data/core
    python3 -I .plans/scripts/barangay-centroid-probe.py \
        $D/barangays.json $D/cities.json vendor/public/ph-address/barangays

⚠️ Run it with `-I` and from OUTSIDE the package directory, passing paths as arguments:
downloaded data is untrusted input, and an interpreter started inside that tree would load
code from it on import.

WHAT IT MEASURES
 1. the `coordinate_source` distribution over all rows        — is the provenance usable?
 2. the join to booker's own barangay codes                   — does it cover what we ship?
 3. whether a barangay's coordinate equals its parent city's  — the "in disguise" test
 4. distance from each barangay to its parent city centroid   — an independent plausibility
                                                                check, the same shape as
                                                                U3's GeoNames cross-check
"""
import collections
import glob
import json
import math
import os
import statistics
import sys

EARTH_RADIUS_KM = 6371.0088


def haversine_km(a, b):
    lat1, lat2 = math.radians(a[0]), math.radians(b[0])
    dlat, dlng = lat2 - lat1, math.radians(b[1] - a[1])
    h = math.sin(dlat / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlng / 2) ** 2
    return 2 * EARTH_RADIUS_KM * math.asin(math.sqrt(h))


def coord(row):
    c = row.get("coordinate") or {}
    if c.get("latitude") is None:
        return None
    return (c["latitude"], c["longitude"])


def main(barangays_path, cities_path, shard_dir):
    bgy = json.load(open(barangays_path, encoding="utf-8"))
    cities = json.load(open(cities_path, encoding="utf-8"))
    city_pos = {c["psgc_code"]: coord(c) for c in cities if coord(c)}

    print(f"barangay rows in package : {len(bgy)}")
    print(f"rows with a coordinate   : {sum(1 for r in bgy if coord(r))}")

    # 1 — provenance distribution
    print("\n=== 1. coordinate_source distribution ===")
    dist = collections.Counter(r.get("coordinate_source") or "<none>" for r in bgy)
    for src, n in dist.most_common():
        print(f"  {src:<34} {n:>7}  {n / len(bgy) * 100:5.1f}%")

    # 2 — join coverage against the barangay codes the apps actually ship.
    # ⚠️ Join on `correspondence_code` (9-digit), NOT `psgc_code` (10-digit): booker's
    # dataset and `vendors.barangay_code` use the 9-digit form. Same trap as near-me F9/F10.
    booker = set()
    for f in glob.glob(os.path.join(shard_dir, "*.json")):
        for b in json.load(open(f, encoding="utf-8")):
            booker.add(b["code"])
    by_corr = {r["correspondence_code"]: r for r in bgy if r.get("correspondence_code")}
    joined = booker & set(by_corr)
    print(f"\n=== 2. join coverage ===\n  booker barangay codes : {len(booker)}")
    print(f"  joined                : {len(joined)}  ({len(joined) / len(booker) * 100:.1f}%)")
    jd = collections.Counter(by_corr[c].get("coordinate_source") or "<none>" for c in joined)
    for src, n in jd.most_common():
        print(f"    {src:<32} {n:>7}  {n / len(booker) * 100:5.1f}% of booker's")

    # 3 — the "city centroid in disguise" test
    print("\n=== 3. is a barangay's coordinate just its parent city's? ===")
    tally = collections.defaultdict(lambda: [0, 0])
    for r in bgy:
        c, p = coord(r), city_pos.get(r.get("city_code"))
        if not c:
            continue
        t = tally[r.get("coordinate_source") or "<none>"]
        t[1] += 1
        if p and (round(c[0], 6), round(c[1], 6)) == (round(p[0], 6), round(p[1], 6)):
            t[0] += 1
    for src, (same, tot) in sorted(tally.items(), key=lambda kv: -kv[1][1]):
        print(f"  {src:<34} {same:>6}/{tot:<6} = {same / tot * 100:5.1f}% identical to parent")

    # 4 — plausibility: a real barangay centroid sits a few km from the city centroid,
    # neither 0 km (that would BE the city centroid) nor absurdly far.
    print("\n=== 4. distance to parent city centroid ===")
    per, far = collections.defaultdict(list), []
    for r in bgy:
        c, p = coord(r), city_pos.get(r.get("city_code"))
        if not c or not p:
            continue
        d = haversine_km(c, p)
        per[r.get("coordinate_source") or "<none>"].append(d)
        if d > 60:
            far.append((round(d), r.get("name"), r.get("coordinate_source")))
    print(f"  {'source':<34} {'n':>6} {'median':>8} {'p95':>8} {'max':>8}")
    for src, ds in sorted(per.items(), key=lambda kv: -len(kv[1])):
        ds.sort()
        p95 = ds[int(len(ds) * 0.95)] if len(ds) > 20 else ds[-1]
        print(f"  {src:<34} {len(ds):>6} {statistics.median(ds):>8.2f} {p95:>8.2f} {max(ds):>8.1f}")
    print(f"\n  implausible (>60 km from parent city): {len(far)}")
    for d, n, s in sorted(far, reverse=True)[:8]:
        print(f"    {d} km — {n} | {s}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3])
